//! Writes `packaging/languages.isi`, the texts of the Windows installer, from the locale files:
//! `cargo run -p shotoshot-text --example inno`. `cargo test` fails while the committed file
//! differs from what this writes.

use shotoshot_text::{Key, Language, LanguageChoice, tr_in};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The languages of the installer's wizard, as named in `[Languages]` of
/// `packaging/shotoshot.iss`, in table order; English first, as Inno's default. Inno Setup 6
/// ships no official Chinese: both come from its contributed translations, kept in
/// `packaging/languages/`.
const WIZARD: [(&str, Language); 15] = [
    ("english", Language::En),
    ("chinesesimplified", Language::ZhHans),
    ("russian", Language::Ru),
    ("spanish", Language::Es),
    ("brazilianportuguese", Language::PtBr),
    ("german", Language::De),
    ("japanese", Language::Ja),
    ("french", Language::Fr),
    ("polish", Language::Pl),
    ("korean", Language::Ko),
    ("chinesetraditional", Language::ZhHant),
    ("turkish", Language::Tr),
    ("ukrainian", Language::Uk),
    ("italian", Language::It),
    ("czech", Language::Cs),
];

/// Inno's custom message name of each installer text.
const MESSAGES: [(&str, Key); 4] = [
    ("LanguagePageTitle", Key::InstallerLanguageTitle),
    ("LanguagePageDescription", Key::InstallerLanguageDescription),
    ("LanguageAuto", Key::InstallerLanguageAuto),
    ("ShotoFile", Key::InstallerShotoFile),
];

/// A custom message is one line, and `%` would start one of Inno's arguments.
fn checked(name: &str, text: &str) -> String {
    assert!(
        !text.contains(['\n', '\r', '%', '{', '}']),
        "{name}: `{text}` cannot be an Inno custom message"
    );
    text.to_string()
}

fn render() -> String {
    let mut out = String::from('\u{feff}');
    out.push_str(
        "; Generated by `cargo run -p shotoshot-text --example inno` from\n\
         ; crates/shotoshot-text/locales: do not edit. Included by shotoshot.iss.\n\
         [CustomMessages]\n\
         ; The choices of the language page: the automatic one, then each language under its\n\
         ; own name (never translated), in the order of the application's language menu.\n",
    );
    let _ = writeln!(out, "ChoiceCount={}", LanguageChoice::ALL.len());
    for (index, choice) in LanguageChoice::ALL.into_iter().enumerate() {
        let _ = writeln!(out, "ChoiceTag{index}={}", choice.encode());
        if let LanguageChoice::Fixed(language) = choice {
            let name = checked("ChoiceName", language.native_name());
            let _ = writeln!(out, "ChoiceName{index}={name}");
        }
    }
    for (inno, language) in WIZARD {
        let _ = writeln!(out, "; {}", language.tag());
        for (name, key) in MESSAGES {
            let text = checked(name, tr_in(language, key));
            let _ = writeln!(out, "{inno}.{name}={text}");
        }
    }
    out
}

fn target() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packaging/languages.isi")
}

fn main() {
    let path = target();
    std::fs::write(&path, render()).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    println!("Wrote {}", path.display());
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn inno_messages_are_current() {
        // Read at build time: the test binary also runs where the source tree is absent (Pi).
        let committed: &[u8] = include_bytes!("../../../packaging/languages.isi");
        assert!(
            committed == render().as_bytes(),
            "packaging/languages.isi is stale: run `cargo run -p shotoshot-text --example inno`"
        );
    }

    #[test]
    fn wizard_languages_are_distinct_and_english_comes_first() {
        assert_eq!(WIZARD[0], ("english", Language::En));
        for (index, (name, language)) in WIZARD.iter().enumerate() {
            for (other_name, other) in &WIZARD[index + 1..] {
                assert!(name != other_name && language != other, "{name}");
            }
        }
        let order: Vec<usize> = WIZARD.iter().map(|(_, l)| *l as usize).collect();
        assert!(
            order.windows(2).all(|pair| pair[0] < pair[1]),
            "table order"
        );
    }
}
